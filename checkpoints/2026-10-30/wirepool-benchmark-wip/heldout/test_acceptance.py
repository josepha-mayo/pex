"""Independent black-box acceptance oracle, only public TASK.md requirements.

Wire is an AUTHORED transport, not a server/client library. The oracle uses
literal wire bytes and observed leases; it never imports reference internals.
"""
import asyncio
import unittest
from wirepool import (Client, Connection, Pool, Decoder, NEED_MORE,
                      encode_command, CommandError, ProtocolError, PoolClosed)


async def barrier():
    loop = asyncio.get_running_loop()
    event = asyncio.Event()
    loop.call_soon(event.set)
    await event.wait()


async def finish(awaitable):
    return await asyncio.wait_for(awaitable, 2)


class Wire:
    def __init__(self, plans=(), send_gate=None, send_error=None, recv_error=None):
        self.plans = list(plans)
        self.incoming = asyncio.Queue()
        self.reads = asyncio.Queue()
        self.sent_event = asyncio.Event()
        self.writes = []
        self.send_gate, self.send_error, self.recv_error = send_gate, send_error, recv_error
        self.closed = False
        self.close_calls = 0
        self.active_io = 0

    async def send(self, data):
        if self.closed:
            raise ConnectionError('write after close')
        self.active_io += 1
        try:
            self.writes.append(data)
            if self.plans:
                for chunk in self.plans.pop(0):
                    self.incoming.put_nowait(chunk)
            self.sent_event.set()
            if self.send_gate is not None:
                await self.send_gate.wait()
            if self.send_error is not None:
                raise self.send_error
        finally:
            self.active_io -= 1

    async def recv(self):
        self.reads.put_nowait(True)
        self.active_io += 1
        try:
            if self.recv_error is not None:
                raise self.recv_error
            return await self.incoming.get()
        finally:
            self.active_io -= 1

    def close(self):
        if not self.closed:
            self.closed = True
            self.close_calls += 1
            self.incoming.put_nowait(b'')


class Abort(BaseException):
    pass


class Acceptance(unittest.IsolatedAsyncioTestCase):
    async def test_01_codec_fragmentation_grammar_and_limits(self):
        # Literal oracle: not generated by the candidate encoder/parser.
        frame = b'*4\r\n$5\r\na\x00b\r\n\r\n$-1\r\n*2\r\n:-42\r\n+z\r\n*0\r\n'
        expected = [b'a\x00b\r\n', None, [-42, b'z'], []]
        for split in range(len(frame) + 1):
            with self.subTest(split=split):
                decoder = Decoder()
                decoder.feed(frame[:split])
                if split < len(frame):
                    self.assertIs(decoder.pop(), NEED_MORE)
                    decoder.feed(frame[split:])
                self.assertEqual(decoder.pop(), expected)
                self.assertIs(decoder.pop(), NEED_MORE)
        decoder = Decoder(max_bulk=3, max_depth=2)
        decoder.feed(b'*1\r\n*1\r\n$3\r\nx\r\n\r\n:0007\r\n')
        self.assertEqual(decoder.pop(), [[b'x\r\n']])
        self.assertEqual(decoder.pop(), 7)
        invalid = [b'!x', b':+1\r\n', b':1_0\r\n', b': 1\r\n',
                   b'$-2\r\n', b'*-2\r\n', b'$4\r\n', b'$1\r\nx!!',
                   b'*1\r\n*1\r\n*0\r\n']
        for raw in invalid:
            with self.subTest(invalid=raw):
                d = Decoder(max_bulk=3, max_depth=2); d.feed(raw)
                with self.assertRaises(ProtocolError): d.pop()
        for value in (0, -1, True, 1.5):
            with self.assertRaises(ValueError): Decoder(max_bulk=value)
            with self.assertRaises(ValueError): Decoder(max_depth=value)
        with self.assertRaises(TypeError): Decoder().feed(bytearray(b'+x\r\n'))
        self.assertEqual(encode_command(['é', b'\r\n', -2]),
                         b'*3\r\n$2\r\n\xc3\xa9\r\n$2\r\n\r\n\r\n$2\r\n-2\r\n')

    async def test_02_pipeline_errors_are_values_until_fully_drained(self):
        wire = Wire([[b'-FIRST\r\n:8\r\n-SECOND\r\n'],
                     [b'+fresh\r\n'], [b'-E0\r\n*2\r\n:3\r\n-NEST\r\n$-1\r\n'],
                     [b'-ORDINARY\r\n'], [b'+reused\r\n']])
        creations = []
        async def factory(): creations.append(wire); return wire
        pool = Pool(factory, 1); client = Client(pool)
        with self.assertRaisesRegex(CommandError, '^FIRST$'):
            await finish(client.pipeline([('A',), ('B',), ('C',)]))
        self.assertEqual(await finish(client.execute('D')), b'fresh')
        values = await finish(client.pipeline([('E',), ('F',), ('G',)], return_exceptions=True))
        self.assertIsInstance(values[0], CommandError)
        self.assertEqual(str(values[0]), 'E0')
        self.assertEqual(values[1][0], 3)
        self.assertIsInstance(values[1][1], CommandError)
        self.assertIsNone(values[2])
        with self.assertRaisesRegex(CommandError, '^ORDINARY$'):
            await finish(client.execute('H'))
        self.assertEqual(await finish(client.execute('I')), b'reused')
        self.assertEqual(len(creations), 1)
        self.assertEqual(wire.writes[0], b'*1\r\n$1\r\nA\r\n*1\r\n$1\r\nB\r\n*1\r\n$1\r\nC\r\n')
        self.assertEqual(len(wire.writes), 5)
        self.assertFalse(wire.closed)
        await pool.aclose()

    async def test_03_cancel_at_send_and_partial_reply_boundaries(self):
        cases = [('send', None), ('header', b'$'), ('body', b'$5\r\nold'),
                 ('trailer', b'$3\r\nold\r'), ('pipeline', b':1\r\n$4\r\nla')]
        for label, prefix in cases:
            with self.subTest(boundary=label):
                gate = asyncio.Event() if label == 'send' else None
                old = Wire([] if prefix is None else [[prefix]], send_gate=gate)
                new = Wire([[b'$3\r\nnew\r\n']])
                wires = iter([old, new]); creations = []
                async def factory():
                    wire = next(wires); creations.append(wire); return wire
                pool = Pool(factory, 1); client = Client(pool)
                operation = client.pipeline([('ONE',), ('TWO',)]) if label == 'pipeline' else client.execute('OLD')
                task = asyncio.create_task(operation)
                if label == 'send':
                    await finish(old.sent_event.wait())
                else:
                    await finish(old.reads.get())
                    await finish(old.reads.get())  # blocked after consuming the incomplete prefix
                task.cancel()
                with self.assertRaises(asyncio.CancelledError): await finish(task)
                self.assertTrue(old.closed)
                self.assertEqual(old.active_io, 0, 'no shielded/detached I/O remains')
                old.incoming.put_nowait(b'late\r\n')
                self.assertEqual(await finish(client.execute('NEW')), b'new')
                self.assertEqual(len(creations), 2)
                self.assertEqual(len(old.writes), 1, 'cancelled work must not replay')
                await pool.aclose()

    async def test_04_waiter_cancellation_before_and_after_handoff(self):
        made = []
        async def factory():
            wire = Wire(); made.append(wire); return wire
        pool = Pool(factory, 1)
        held = await pool.acquire()
        first = asyncio.create_task(pool.acquire())
        second = asyncio.create_task(pool.acquire())
        survivor = asyncio.create_task(pool.acquire())
        await barrier()
        first.cancel()
        with self.assertRaises(asyncio.CancelledError): await first
        held.release()      # publish the handoff without yielding to its recipient
        second.cancel()     # recipient has not resumed yet
        with self.assertRaises(asyncio.CancelledError): await second
        lease = await finish(survivor)
        self.assertIs(lease.connection, held.connection)
        self.assertFalse(made[0].closed)
        self.assertEqual(len(made), 1)
        lease.release(); await pool.aclose()
        # The same cancellation boundary when a dead connection frees a factory slot.
        pool = Pool(factory, 1); held = await pool.acquire()
        second = asyncio.create_task(pool.acquire())
        survivor = asyncio.create_task(pool.acquire()); await barrier()
        held.connection.close(); held.release()
        second.cancel()
        with self.assertRaises(asyncio.CancelledError): await second
        lease = await finish(survivor)
        self.assertFalse(lease.connection.closed)
        lease.release(); await pool.aclose()
        # Cancellation already delivered to a not-yet-returned acquire takes precedence.
        pool = Pool(factory, 1); held = await pool.acquire()
        waiter = asyncio.create_task(pool.acquire()); await barrier()
        await pool.aclose()
        if not waiter.done():
            waiter.cancel()
            with self.assertRaises(asyncio.CancelledError): await waiter
        else:
            with self.assertRaises(PoolClosed): await waiter
        held.release()

    async def test_05_inflight_factory_capacity_failure_cancel_and_shutdown(self):
        gate = asyncio.Event(); entered = asyncio.Queue(); active = 0; high = 0; made = []
        async def factory():
            nonlocal active, high
            active += 1; high = max(high, active); entered.put_nowait(active)
            try:
                await gate.wait()
                wire = Wire(); made.append(wire); return wire
            finally: active -= 1
        pool = Pool(factory, 2)
        a, b, c = [asyncio.create_task(pool.acquire()) for _ in range(3)]
        await finish(entered.get()); await finish(entered.get()); await barrier()
        self.assertEqual(active, 2)
        self.assertFalse(c.done())
        a.cancel()
        with self.assertRaises(asyncio.CancelledError): await a
        await finish(entered.get())
        self.assertEqual(high, 2)
        gate.set()
        lb, lc = await finish(b), await finish(c)
        self.assertIsNot(lb.connection, lc.connection)
        lb.release(); lc.release(); await pool.aclose()
        error = OSError('factory failed'); calls = 0
        async def faulty():
            nonlocal calls
            calls += 1
            if calls == 1: raise error
            return Wire()
        pool = Pool(faulty, 1)
        with self.assertRaises(OSError) as got: await pool.acquire()
        self.assertIs(got.exception, error)
        lease = await finish(pool.acquire()); lease.release(); await pool.aclose()
        gate = asyncio.Event(); entered = asyncio.Event(); returned = Wire()
        async def late_factory():
            entered.set(); await gate.wait(); return returned
        pool = Pool(late_factory, 1)
        task = asyncio.create_task(pool.acquire()); await finish(entered.wait())
        await finish(pool.aclose())
        self.assertFalse(task.done(), 'shutdown must not wait for or cancel the factory')
        gate.set()
        with self.assertRaises(PoolClosed): await finish(task)
        self.assertTrue(returned.closed)

    async def test_06_fifo_no_barging_double_release_and_close_handoff(self):
        created = []
        async def factory():
            wire = Wire(); created.append(wire); return wire
        pool = Pool(factory, 1); initial = await pool.acquire()
        first = asyncio.create_task(pool.acquire()); second = asyncio.create_task(pool.acquire())
        arrive = asyncio.Event()
        async def late_arrival():
            await arrive.wait()
            return await pool.acquire()
        newcomer = asyncio.create_task(late_arrival())
        await barrier()
        arrive.set()  # ready BEFORE release wakes the promised recipient
        initial.release(); initial.release()
        await barrier()
        self.assertTrue(first.done()); self.assertFalse(second.done()); self.assertFalse(newcomer.done())
        one = await first
        self.assertEqual(len(created), 1)
        one.release(); two = await finish(second)
        self.assertFalse(newcomer.done())
        two.release()  # newcomer now owns an assigned connection even before it resumes
        await pool.aclose()
        three = await finish(newcomer)
        self.assertFalse(three.connection.closed)
        three.release(); self.assertTrue(created[0].closed)
        with self.assertRaises(PoolClosed): await pool.acquire()
        for value in (0, -1, True, 1.25):
            with self.assertRaises(ValueError): Pool(factory, value)

    async def test_07_transport_protocol_and_baseexception_cleanup(self):
        for where in ('send', 'recv', 'protocol', 'eof', 'baseexception'):
            with self.subTest(where=where):
                error = Abort('stop') if where == 'baseexception' else OSError('wire failure')
                old = Wire(send_error=error if where in ('send', 'baseexception') else None,
                           recv_error=error if where == 'recv' else None,
                           plans=[[b'$2\r\nx', b'']] if where == 'eof' else
                                 [[b'$1\r\nx??']] if where == 'protocol' else [])
                new = Wire([[b':99\r\n']]); wires = iter([old, new])
                async def factory(): return next(wires)
                pool = Pool(factory, 1); client = Client(pool)
                expected = ProtocolError if where == 'protocol' else ConnectionError if where == 'eof' else type(error)
                with self.assertRaises(expected): await finish(client.execute('OLD'))
                self.assertTrue(old.closed)
                self.assertEqual(old.active_io, 0)
                self.assertEqual(await finish(client.execute('NEW')), 99)
                self.assertEqual(len(old.writes), 1)
                await pool.aclose()
        # Connection API retains coalesced subsequent replies; they are not unsolicited-fault tests.
        wire = Wire([[b':11\r\n:12\r\n'], []]); conn = Connection(wire)
        self.assertEqual(await finish(conn.exchange(b'*1\r\n$3\r\nONE\r\n', 1)), [11])
        self.assertEqual(await finish(conn.exchange(b'*1\r\n$3\r\nTWO\r\n', 1)), [12])
        conn.close(); conn.close()
        self.assertEqual(wire.close_calls, 1)
        with self.assertRaises(ConnectionError): await conn.exchange(b'*1\r\n$5\r\nTHREE\r\n', 1)

    async def test_08_concurrent_clients_waiter_cancellation_and_validation(self):
        wire = Wire(); created = []
        async def factory(): created.append(wire); return wire
        pool = Pool(factory, 1); a, b = Client(pool), Client(pool)
        first = asyncio.create_task(a.execute('FIRST'))
        await finish(wire.reads.get())
        canceled = asyncio.create_task(b.execute('MUST_NOT_SEND'))
        next_request = asyncio.create_task(b.execute('NEXT'))
        await barrier(); canceled.cancel()
        with self.assertRaises(asyncio.CancelledError): await canceled
        self.assertFalse(wire.closed)
        self.assertEqual(len(wire.writes), 1)
        with self.assertRaises((TypeError, ValueError)):
            await finish(b.pipeline([('OK',), ('BAD', False)]))
        self.assertEqual(len(wire.writes), 1)
        wire.incoming.put_nowait(b'$5\r\nfirst\r\n')
        self.assertEqual(await finish(first), b'first')
        await finish(wire.reads.get())
        self.assertEqual(len(wire.writes), 2)
        wire.incoming.put_nowait(b'$4\r\nnext\r\n')
        self.assertEqual(await finish(next_request), b'next')
        self.assertEqual(len(created), 1)
        self.assertEqual(await b.pipeline([]), [])
        self.assertEqual(len(wire.writes), 2)
        await pool.aclose()
